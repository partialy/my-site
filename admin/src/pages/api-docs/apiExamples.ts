export function getEndpointExample(endpoint: ApiEndpoint): EndpointExample {
  const key = `${endpoint.method} ${endpoint.path}`;
  const example = examples[key];
  if (!example) throw new Error(`缺少接口示例：${key}`);
  return example;
}

